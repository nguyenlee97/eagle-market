def _sym_hash(symbol: str) -> int:
    return int.from_bytes(hashlib.blake2s(symbol.encode("ascii"), digest_size=4).digest(), "little")


def _det_unit(seed_a: int, seed_b: int) -> float:
    """Fast deterministic pseudo-Gaussian in roughly [-1.0, +1.0] without touching global RNG."""
    x = ((seed_a * 0x9E3779B1) ^ (seed_b * 0x85EBCA77) ^ 0xC2B2AE3D) & 0xFFFFFFFF
    x = ((x >> 16) ^ x) * 0x45D9F3B & 0xFFFFFFFF
    x = ((x >> 16) ^ x) * 0x45D9F3B & 0xFFFFFFFF
    x = (x >> 16) ^ x
    u1 = ((x & 0xFFFF) / 65535.0) - 0.5
    u2 = (((x >> 16) & 0xFFFF) / 65535.0) - 0.5
    return (u1 + u2) * 1.15


def _smart_round(val: float, cfg_decimals: int) -> float:
    """Rounds cleanly so large prices have crisp 2 decimals while sub-$10 assets keep 3-4 decimals."""
    v = max(0.0001, float(val))
    if v >= 100.0:
        d = min(cfg_decimals, 2)
    elif v >= 10.0:
        d = min(max(cfg_decimals, 2), 2)
    elif v >= 1.0:
        d = min(max(cfg_decimals, 3), 4)
    else:
        d = max(cfg_decimals, 4)
    return round(v, d)


def _yearly_from_waypoints(wps: List[Tuple[str, float]]) -> Dict[int, float]:
    """Extracts 2010..2025 yearly anchor dict for 100% legacy compatibility."""
    ords = [_iso_ord(dt_s) for dt_s, _ in wps]
    logs = [math.log(max(1e-6, px)) for _, px in wps]
    out: Dict[int, float] = {}
    for yr in range(2010, 2026):
        q_ord = datetime.date(yr, 6, 15).toordinal()
        idx = bisect.bisect_right(ords, q_ord)
        if idx <= 0:
            val = math.exp(logs[0])
        elif idx >= len(ords):
            val = math.exp(logs[-1])
        else:
            t0, t1 = ords[idx - 1], ords[idx]
            frac = (q_ord - t0) / max(1, t1 - t0)
            val = math.exp(logs[idx - 1] + (logs[idx] - logs[idx - 1]) * frac)
        out[yr] = round(val, 4 if val < 10.0 else 2)
    return out


