def get_historical_ohlcv_window(
    asset_cfg: dict,
    current_date: datetime.date,
    count: int = 48,
) -> List[dict]:
    """
    Synthesizes `count` (48) deterministic, continuous OHLCV candles ending at `current_date`.
    Each candle represents a 12-hour trading session (`0.5` day step) with:
      - Authentic historical trajectory across the preceding 24 days,
      - Multi-wave bull/bear swings so MA7 & MA20 visibly curve and cross,
      - Realistic upper/lower wicks (`h > max(o, c)`, `l < min(o, c)`),
      - Dynamic volume histogram (`v` in 120..1000) correlated with range & regime shocks,
      - Strict minimum vertical span guard so HUD 24-bar charts & 8-bar sparklines never flatten.
    """
    n = max(8, int(count))
    sym = asset_cfg.get("symbol", "ASSET")
    dec = int(asset_cfg.get("decimals", 2))
    vol = float(asset_cfg.get("volatility", 0.018))
    sh = _sym_hash(sym)
    d_ord = current_date.toordinal()
    is_iou = _sync_asset_phase(asset_cfg, d_ord)
    reg_mult, reg_bias, _ = get_market_regime(current_date)

    eff_vol = vol * (0.85 + 0.30 * reg_mult) * (1.28 if is_iou else 1.0)
    raw_closes: List[float] = []
    for i in range(n):
        f_ord = float(d_ord) - (n - 1 - i) * 0.5
        c_val = _base_curve_price_at_float_ord(sym, f_ord, fallback_cfg=asset_cfg)
        # Add subtle regime bias tilt on the final 10 bars during major historical crashes/squeezes
        if i >= n - 10 and abs(reg_bias) > 0.25:
            prog = (i - (n - 10)) / 10.0
            c_val *= (1.0 + reg_bias * vol * 0.45 * prog)
        raw_closes.append(max(0.0008, c_val))

    # Ensure 24-bar HUD chart and 8-bar Watchlist sparkline always have lively dynamic range
    last8 = raw_closes[-8:]
    mid8 = sum(last8) / len(last8)
    min_req_span8 = max(0.00035, mid8 * max(0.014, vol * 0.85))
    cur_span8 = max(last8) - min(last8)
    if cur_span8 < min_req_span8:
        boost = (min_req_span8 - cur_span8) * 0.65
        for k in range(8):
            idx_k = n - 8 + k
            wave = math.sin(k * 1.15 + (sh & 0x3F) * 0.11)
            raw_closes[idx_k] = max(0.0008, raw_closes[idx_k] + boost * wave)

    last24 = raw_closes[-24:] if n >= 24 else raw_closes
    mid24 = sum(last24) / len(last24)
    min_req_span24 = max(0.00075, mid24 * max(0.028, vol * 1.55))
    cur_span24 = max(last24) - min(last24)
    if cur_span24 < min_req_span24:
        m_len = len(last24)
        boost24 = (min_req_span24 - cur_span24) * 0.65
        for k in range(m_len):
            idx_k = n - m_len + k
            wave = math.sin(k * 0.52 + ((sh >> 6) & 0x3F) * 0.13)
            raw_closes[idx_k] = max(0.0008, raw_closes[idx_k] + boost24 * wave)

    # Ensure overall 48-bar delta_pct is never stuck at 0.00%
    if abs(raw_closes[-1] - raw_closes[0]) / max(raw_closes[0], 1e-6) < 0.0035:
        dir_sign = 1.0 if ((sh ^ d_ord) & 1) == 0 else -1.0
        raw_closes[-1] = max(0.0008, raw_closes[-1] * (1.0 + dir_sign * max(0.0085, vol * 0.55)))

    candles: List[dict] = []
    prev_c = raw_closes[0] * (1.0 - _det_unit(sh, d_ord * 4 - n) * eff_vol * 0.42)
    prev_c = max(0.0008, prev_c)

    for i in range(n):
        step_seed = d_ord * 64 + i
        c_raw = raw_closes[i]
        # Small realistic inter-session gap between prev close and new open
        gap = _det_unit(sh ^ 0x5A5A, step_seed) * eff_vol * 0.14
        o_raw = max(0.0008, prev_c * (1.0 + gap))

        # Guarantee visible candle body when open and close happen to sit too close
        body_rel = abs(c_raw - o_raw) / max(o_raw, 1e-6)
        if body_rel < eff_vol * 0.12:
            nudge_dir = 1.0 if _det_unit(sh ^ 0x1337, step_seed) >= 0 else -1.0
            c_raw = max(0.0008, o_raw * (1.0 + nudge_dir * max(0.0022, eff_vol * 0.22)))

        body_hi = max(o_raw, c_raw)
        body_lo = min(o_raw, c_raw)
        body_abs = body_hi - body_lo

        # Asymmetric upper and lower wicks
        u_wick_fac = (0.28 + 0.85 * abs(_det_unit(sh ^ 0xAAAA, step_seed))) * eff_vol * 0.72
        l_wick_fac = (0.28 + 0.85 * abs(_det_unit(sh ^ 0xBBBB, step_seed))) * eff_vol * 0.72
        h_raw = body_hi * (1.0 + u_wick_fac) + body_abs * 0.18
        l_raw = max(0.0005, body_lo * (1.0 - l_wick_fac) - body_abs * 0.18)

        o_px = _smart_round(o_raw, dec)
        c_px = _smart_round(c_raw, dec)
        h_px = _smart_round(max(h_raw, o_px, c_px), dec)
        l_px = _smart_round(min(l_raw, o_px, c_px), dec)

        min_tick = 0.01 if o_px >= 10.0 else (0.001 if o_px >= 1.0 else 0.0001)
        if h_px <= max(o_px, c_px):
            h_px = round(max(o_px, c_px) + min_tick, 4 if o_px < 10.0 else 2)
        if l_px >= min(o_px, c_px) and min(o_px, c_px) > min_tick * 2:
            l_px = round(min(o_px, c_px) - min_tick, 4 if o_px < 10.0 else 2)

        rel_range = (h_px - l_px) / max(o_px, 1e-5)
        vol_score = int(
            min(
                1000.0,
                max(
                    135.0,
                    240.0
                    + (rel_range / max(0.006, eff_vol)) * 310.0
                    + abs(_det_unit(sh ^ 0xCCCC, step_seed)) * 210.0,
                ),
            )
        )
        candles.append({"o": o_px, "h": h_px, "l": l_px, "c": c_px, "v": vol_score})
        prev_c = c_px

    # Final post-rounding check: guarantee `candles[-1]['c']` vs `candles[0]['o']` never rounds to 0.00%
    open0 = candles[0]["o"]
    last_c = candles[-1]["c"]
    if open0 > 0 and round(((last_c - open0) / open0) * 100.0, 2) == 0.0:
        dir_s = 1.0 if ((sh ^ d_ord) & 1) == 0 else -1.0
        bumped = _smart_round(max(0.0008, last_c * (1.0 + dir_s * max(0.0045, vol * 0.35))), dec)
        if bumped == last_c:
            min_t = 0.01 if last_c >= 10.0 else (0.001 if last_c >= 1.0 else 0.0001)
            bumped = _smart_round(max(0.0008, last_c + dir_s * min_t * 2.0), dec)
        candles[-1]["c"] = bumped
        if bumped >= candles[-1]["h"]:
            min_t = 0.01 if bumped >= 10.0 else (0.001 if bumped >= 1.0 else 0.0001)
            candles[-1]["h"] = _smart_round(bumped + min_t, dec)
        if bumped <= candles[-1]["l"] and bumped > 0.0008:
            min_t = 0.01 if bumped >= 10.0 else (0.001 if bumped >= 1.0 else 0.0001)
            candles[-1]["l"] = _smart_round(max(0.0005, bumped - min_t), dec)

    return candles


def step_live_market_candle(
    asset: dict,
    current_date: datetime.date,
    open_price: float,
) -> dict:
    """
    Live 2.0-second intraday OHLCV step for `EagleCompanion.step_simulation()`.
    Generates tradeable multi-candle momentum bursts, pullback retracements, wick spikes,
    and elastic anchoring to the authentic chronological target price.
    """
    sym = asset.get("symbol", "ASSET")
    dec = int(asset.get("decimals", 2))
    vol = float(asset.get("volatility", 0.018))
    d_ord = current_date.toordinal()
    is_iou = _sync_asset_phase(asset, d_ord)

    target = get_chronological_target_price(asset, current_date)
    o = float(open_price) if (open_price and open_price > 0) else target
    reg_mult, reg_bias, _ = get_market_regime(current_date)
    tick_vol = max(0.0025, vol * 0.42 * (0.85 + 0.25 * reg_mult) * (1.20 if is_iou else 1.0))

    # Per-symbol intraday wave state: [momentum, ticks_left, wave_dir, tick_counter]
    st = _LIVE_STATE.get(sym)
    if st is None:
        h0 = _sym_hash(sym)
        init_dir = 1.0 if (h0 & 1) == 0 else -1.0
        st = [0.0, float(3 + (h0 % 5)), init_dir, 0.0]
        _LIVE_STATE[sym] = st

    mom, ticks_left, wave_dir, tick_cnt = st
    tick_cnt += 1.0
    ticks_left -= 1.0
    if ticks_left <= 0.0:
        # Flip or extend intraday mini-trend (3 to 7 candles per wave, occasional breakout burst)
        if random.random() < 0.68:
            wave_dir = -wave_dir
        ticks_left = float(random.randint(3, 7))

    # Elastic historical anchor pull: gentle inside +-8% band, firm outside +-14% band
    rel_dev = (target - o) / max(o, 1e-6)
    if abs(rel_dev) > 0.14:
        anchor_pull = max(-0.12, min(0.12, rel_dev * 0.22))
    else:
        anchor_pull = rel_dev * 0.045

    burst_mult = 1.85 if random.random() < 0.10 else 1.0
    noise = random.gauss(0.0, tick_vol * 0.72 * burst_mult)
    wave_push = wave_dir * tick_vol * 0.34 + reg_bias * tick_vol * 0.08
    mom = 0.38 * mom + 0.62 * (wave_push + noise)
    ret = max(-0.18, min(0.18, anchor_pull + mom))

    # Prevent dead-flat close == open ticks
    if abs(ret) < tick_vol * 0.10:
        ret = (tick_vol * 0.20) * (1.0 if random.random() < 0.5 else -1.0)

    c_raw = max(max(0.0006, target * 0.18), o * (1.0 + ret))
    st[0], st[1], st[2], st[3] = mom, ticks_left, wave_dir, tick_cnt

    body_hi = max(o, c_raw)
    body_lo = min(o, c_raw)
    u_spike = abs(random.gauss(0.0, tick_vol * (0.95 if random.random() < 0.15 else 0.48)))
    l_spike = abs(random.gauss(0.0, tick_vol * (0.95 if random.random() < 0.15 else 0.48)))
    h_raw = body_hi * (1.0 + max(0.0012, u_spike))
    l_raw = max(0.0005, body_lo * (1.0 - max(0.0012, l_spike)))

    o_px = _smart_round(o, dec)
    c_px = _smart_round(c_raw, dec)
    min_tick = 0.01 if o_px >= 10.0 else (0.001 if o_px >= 1.0 else 0.0001)
    if c_px == o_px:
        c_px = _smart_round(max(0.0005, o_px + (min_tick if ret >= 0 else -min_tick)), dec)

    h_px = _smart_round(max(h_raw, o_px, c_px), dec)
    l_px = _smart_round(min(l_raw, o_px, c_px), dec)
    if h_px <= max(o_px, c_px):
        h_px = _smart_round(max(o_px, c_px) + min_tick, dec)
    if l_px >= min(o_px, c_px) and min(o_px, c_px) > min_tick * 2:
        l_px = _smart_round(min(o_px, c_px) - min_tick, dec)

    rel_rng = (h_px - l_px) / max(o_px, 1e-5)
    vol_bar = int(min(1000.0, max(130.0, 230.0 + (rel_rng / max(0.004, tick_vol)) * 280.0 + random.uniform(0, 140))))
    return {"o": o_px, "h": h_px, "l": l_px, "c": c_px, "v": vol_bar}


def _build_fresh_runtime_asset(cfg: dict, group: str, current_date: datetime.date, old_entry: Optional[dict] = None) -> dict:
    asset_copy = dict(cfg)
    candles = get_historical_ohlcv_window(asset_copy, current_date, count=48)
    dec = int(asset_copy.get("decimals", 2))
    p = _smart_round(float(candles[-1]["c"]), dec)
    open_0 = float(candles[0]["o"] or p or 1.0)
    spot_qty = float(old_entry.get("spot_qty", 0.0)) if isinstance(old_entry, dict) else 0.0
    spot_cost = float(old_entry.get("spot_cost", 0.0)) if isinstance(old_entry, dict) else 0.0
    spot_val = round(spot_qty * p, 2)
    spot_pnl = round(spot_val - spot_cost, 2) if spot_qty > 0 else 0.0
    spot_pnl_pct = round((spot_pnl / spot_cost) * 100.0, 2) if (spot_qty > 0 and spot_cost > 0) else 0.0
    return {
        **asset_copy,
        "market_group": group,
        "price": p,
        "delta_pct": round(((p - open_0) / open_0) * 100.0, 2),
        "candles": candles,
        "spot_qty": spot_qty,
        "spot_cost": spot_cost,
        "spot_val": spot_val,
        "spot_pnl": spot_pnl,
        "spot_pnl_pct": spot_pnl_pct,
    }


def ensure_market_catalog_migrated(
    stocks_market: Optional[dict],
    crypto_market: Optional[dict],
    current_date: datetime.date,
) -> None:
    """
    In-place migration hook for durable snapshots (`cleo/EagleDialogue/phone-wallet.json`).
    When `WalletStore._apply()` loads an older 16-stock / 8-crypto wallet snapshot and calls
    `generate_daily_newspaper()`, this seamlessly upgrades both dicts in-place to the full
    35-stock + 16-crypto v6.3 catalog while preserving existing player `spot_qty` & `spot_cost`.
    """
    if isinstance(stocks_market, dict):
        exp_s = [c["symbol"] for c in STOCK_AND_COMMODITY_ASSETS]
        sample_s = next(iter(stocks_market.values()), None)
        if list(stocks_market.keys()) != exp_s or not isinstance(sample_s, dict) or "live_name" not in sample_s:
            alias_map = {"GOOGL": "GOOG", "BRK.B": "BRK"}
            rebuilt_s = {}
            for cfg in STOCK_AND_COMMODITY_ASSETS:
                sym = cfg["symbol"]
                old_e = stocks_market.get(sym) or stocks_market.get(alias_map.get(sym, ""))
                rebuilt_s[sym] = _build_fresh_runtime_asset(cfg, "stocks", current_date, old_entry=old_e)
            stocks_market.clear()
            stocks_market.update(rebuilt_s)

    if isinstance(crypto_market, dict):
        exp_c = [c["symbol"] for c in CRYPTO_ASSETS]
        sample_c = next(iter(crypto_market.values()), None)
        if list(crypto_market.keys()) != exp_c or not isinstance(sample_c, dict) or "live_name" not in sample_c:
            rebuilt_c = {}
            for cfg in CRYPTO_ASSETS:
                sym = cfg["symbol"]
                old_e = crypto_market.get(sym)
                rebuilt_c[sym] = _build_fresh_runtime_asset(cfg, "crypto", current_date, old_entry=old_e)
            crypto_market.clear()
            crypto_market.update(rebuilt_c)
